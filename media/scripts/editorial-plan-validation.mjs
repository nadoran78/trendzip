export const EDITORIAL_PLAN_VALIDATION_CODES = Object.freeze({
  UNKNOWN_PRIMARY_KEYWORD_ID: "UNKNOWN_PRIMARY_KEYWORD_ID",
  UNKNOWN_RELATED_KEYWORD_ID: "UNKNOWN_RELATED_KEYWORD_ID",
  UNKNOWN_EVIDENCE_VIDEO_ID: "UNKNOWN_EVIDENCE_VIDEO_ID",
  INVALID_EVIDENCE_EXCERPT: "INVALID_EVIDENCE_EXCERPT",
  EDITORIAL_SELECTION_CONTRACT_VIOLATIONS: "EDITORIAL_SELECTION_CONTRACT_VIOLATIONS",
  REPAIR_NO_EFFECT: "REPAIR_NO_EFFECT",
});

const REPAIRABLE_EDITORIAL_PLAN_VALIDATION_CODES = new Set([
  EDITORIAL_PLAN_VALIDATION_CODES.UNKNOWN_PRIMARY_KEYWORD_ID,
  EDITORIAL_PLAN_VALIDATION_CODES.UNKNOWN_RELATED_KEYWORD_ID,
  EDITORIAL_PLAN_VALIDATION_CODES.UNKNOWN_EVIDENCE_VIDEO_ID,
  EDITORIAL_PLAN_VALIDATION_CODES.INVALID_EVIDENCE_EXCERPT,
  EDITORIAL_PLAN_VALIDATION_CODES.EDITORIAL_SELECTION_CONTRACT_VIOLATIONS,
]);

export class EditorialPlanValidationError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = "EditorialPlanValidationError";
    this.code = code;
    this.details = Object.freeze({ ...details });
  }
}

export function shouldRepairEditorialPlan(error) {
  if (!(error instanceof EditorialPlanValidationError)) {
    return false;
  }
  return REPAIRABLE_EDITORIAL_PLAN_VALIDATION_CODES.has(error.code);
}
